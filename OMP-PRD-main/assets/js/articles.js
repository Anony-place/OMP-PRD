  function routeFromHash() {
    var h = location.hash || '';
    if (h.slice(0, 2) !== '#/') return null;
    var rest = h.slice(2);
    if (rest.slice(0, 2) === 'c/') {
      var cat = rest.slice(2).split(/[\/?&]/)[0];
      try { return { cat: decodeURIComponent(cat) }; } catch (e) { return { cat: cat }; }
    }
    var slug = '';
    try { slug = decodeURIComponent(rest); } catch (e) { slug = rest; }
    return { slug: slug, invalid: !safeSlug(slug), legacy: true };
  }

