/* ============================================================
   OMP Firebase Cloud Functions.

   `sitemap` is a thin hosting bridge, NOT the sitemap's source of truth.
   Firebase Hosting can only rewrite /sitemap.xml to a static file or to
   one of its own functions, so this function exists purely to serve the
   Supabase Edge Function's output on the site's own domain:

       /sitemap.xml  →  this function  →  supabase/functions/sitemap

   Resolution order:
     1. GET the Supabase Edge Function (SITEMAP_EDGE_URL) — dynamic,
        always current, generated by supabase/functions/sitemap.
     2. If that fails, query Supabase REST from here and build the XML
        with the same shared core (functions/sitemap-core.mjs, a synced
        copy of supabase/functions/sitemap/sitemap-core.mjs).
     3. If the database is unreachable too, emit the static-route-only
        sitemap so crawlers never see a 500 or a 404.

   Only the publishable key is used. RLS — not this file — is what keeps
   drafts out of the sitemap.
   ============================================================ */

const functions = require('firebase-functions');

const SUPABASE_URL = process.env.SUPABASE_URL || 'https://aeehfulikupskyrvcpzb.supabase.co';
const SUPABASE_PUBLISHABLE_KEY = process.env.SUPABASE_PUBLISHABLE_KEY || 'sb_publishable_s3n2U32MNB4PvHx0GolyqA_wlkzD6eR';

const SITE = (process.env.SITE_ORIGIN || 'https://oopsmypassword.com').replace(/\/+$/, '');
const STATIC_LASTMOD = process.env.STATIC_LASTMOD || '2026-08-23';

/* Set with:
   firebase functions:config:set sitemap.edge_url="https://<ref>.supabase.co/functions/v1/sitemap"
   …or simply export SITEMAP_EDGE_URL before deploying. */
const EDGE_URL =
  process.env.SITEMAP_EDGE_URL ||
  (functions.config() && functions.config().sitemap && functions.config().sitemap.edge_url) ||
  'https://aeehfulikupskyrvcpzb.supabase.co/functions/v1/sitemap';

const EDGE_TIMEOUT_MS = 8000;
const ROW_LIMIT = 2000;

const ARTICLE_FIELDS = 'slug,status,published_at,updated_at,created_at';
const PRODUCT_FIELDS = 'slug,name,status,published_at,updated_at,created_at';

/* Loaded lazily so a CommonJS entry can still use the ESM core. */
let corePromise = null;
function getCore() {
  if (!corePromise) corePromise = import('./sitemap-core.mjs');
  return corePromise;
}

function respond(res, xml, { cacheControl, state }) {
  res.set('Content-Type', 'application/xml; charset=utf-8');
  res.set('Cache-Control', cacheControl);
  res.set('X-Content-Type-Options', 'nosniff');
  res.set('X-Robots-Tag', 'noindex');
  res.set('X-Sitemap-State', state);
  return res.status(200).send(xml);
}

/* ---------- 1. ask the Supabase Edge Function ---------- */

async function fromEdgeFunction() {
  if (!EDGE_URL) return null;
  const controller = typeof AbortController === 'function' ? new AbortController() : null;
  const timer = controller ? setTimeout(() => { try { controller.abort(); } catch (e) { /* ignore */ } }, EDGE_TIMEOUT_MS) : null;
  try {
    const res = await fetch(EDGE_URL, controller ? { signal: controller.signal, headers: { accept: 'application/xml' } } : undefined);
    if (!res || !res.ok) return null;
    const text = await res.text();
    /* Sanity gate: never relay an error page or an HTML login screen as
       if it were a sitemap. */
    if (!text || text.indexOf('<urlset') === -1) return null;
    return text;
  } catch (error) {
    console.error('sitemap: edge function unreachable:', error && error.message);
    return null;
  } finally {
    if (timer) clearTimeout(timer);
  }
}

/* ---------- 2. fall back to querying Supabase directly ---------- */

async function rowsFromRest(table, fields) {
  const url =
    `${SUPABASE_URL}/rest/v1/${table}` +
    `?select=${encodeURIComponent(fields)}` +
    `&status=eq.published` +
    `&limit=${ROW_LIMIT}`;
  const res = await fetch(url, {
    headers: {
      apikey: SUPABASE_PUBLISHABLE_KEY,
      Authorization: `Bearer ${SUPABASE_PUBLISHABLE_KEY}`,
      Accept: 'application/json'
    }
  });
  if (!res.ok) throw new Error(`${table} query failed: HTTP ${res.status}`);
  const rows = await res.json();
  return Array.isArray(rows) ? rows : [];
}

async function fromSupabaseRest(core) {
  const [articles, products] = await Promise.all([
    rowsFromRest('articles', ARTICLE_FIELDS),
    rowsFromRest('products', PRODUCT_FIELDS)
  ]);
  return core.buildSitemapXml({ articles, products, site: SITE, staticLastmod: STATIC_LASTMOD });
}

/* ---------- handler ---------- */

exports.sitemap = functions
  .runWith({ timeoutSeconds: 30, memory: '256MB' })
  .https.onRequest(async (req, res) => {
    if (req.method !== 'GET' && req.method !== 'HEAD') {
      res.set('Allow', 'GET, HEAD');
      return res.status(405).send('');
    }

    const xml = await fromEdgeFunction();
    if (xml) {
      return respond(res, xml, {
        cacheControl: 'public, max-age=300, stale-while-revalidate=86400',
        state: 'edge'
      });
    }

    try {
      const core = await getCore();
      const fallbackXml = await fromSupabaseRest(core);
      return respond(res, fallbackXml, {
        cacheControl: 'public, max-age=300, stale-while-revalidate=3600',
        state: 'rest-fallback'
      });
    } catch (error) {
      console.error('sitemap: REST fallback failed:', error && error.message);
    }

    /* Static routes only — always valid, never a 404/500. */
    try {
      const core = await getCore();
      return respond(res, core.buildSitemapXml({ site: SITE, staticLastmod: STATIC_LASTMOD }), {
        cacheControl: 'public, max-age=60',
        state: 'static-fallback'
      });
    } catch (error) {
      console.error('sitemap: core module failed to load:', error && error.message);
      return res.status(503).send('');
    }
  });
