#!/usr/bin/env node
/* ============================================================
   public.redirects -> content/redirects.json

   The panel writes a row when a published article's slug changes. This script
   turns those rows into a committed file, which build-vercel-config.mjs then
   merges into vercel.json. Nothing here needs a secret: these are request
   paths, and they are readable by design.

   Run by .github/workflows/publish-content.yml before the build.
   Run by hand after adding rows in the SQL editor.

     node scripts/sync-redirects.mjs           # write the file
     node scripts/sync-redirects.mjs --check   # fail if it is stale
   ============================================================ */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'content', 'redirects.json');
const SUPABASE_URL = (process.env.SUPABASE_URL || 'https://aeehfulikupskyrvcpzb.supabase.co').replace(/\/+$/, '');
const KEY = process.env.SUPABASE_PUBLISHABLE_KEY || 'sb_publishable_s3n2U32MNB4PvHx0GolyqA_wlkzD6eR';

const check = process.argv.includes('--check');

async function fetchRedirects() {
  const url = `${SUPABASE_URL}/rest/v1/redirects?select=from_path,to_path,status_code&order=from_path.asc`;
  const response = await fetch(url, {
    headers: { apikey: KEY, Authorization: `Bearer ${KEY}`, Accept: 'application/json' },
    signal: AbortSignal.timeout(20000),
  });
  if (!response.ok) throw new Error(`Supabase returned HTTP ${response.status}`);
  return response.json();
}

const rows = await fetchRedirects();
const redirects = rows
  .map((row) => ({
    from: String(row.from_path),
    to: String(row.to_path),
    status: Number(row.status_code) === 308 ? 308 : 301,
  }))
  /* A rule that points at itself is a loop, and a rule without a leading slash
     would be silently ignored by both hosts. Drop them here rather than let them
     reach the generator, where they would be invisible. */
  .filter((rule) => rule.from !== rule.to && rule.from.startsWith('/') && /^(\/|https:\/\/)/.test(rule.to))
  .sort((a, b) => a.from.localeCompare(b.from));

const payload = JSON.stringify({
  note: 'Generated by scripts/sync-redirects.mjs from public.redirects. Do not edit by hand.',
  redirects,
}, null, 2) + '\n';

const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
if (current === payload) {
  console.log(`redirects.json is up to date (${redirects.length} rule(s))`);
  process.exit(0);
}
if (check) {
  console.error(`redirects.json is stale - run: node scripts/sync-redirects.mjs`);
  process.exit(1);
}
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, payload);
console.log(`redirects.json written (${redirects.length} rule(s))`);
